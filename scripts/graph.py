#!/usr/bin/env python3
"""Generate curriculum/graph.md (Mermaid prerequisite graph) from curriculum/concepts.yaml.

Usage: python scripts/graph.py          # rewrite curriculum/graph.md
       python scripts/graph.py --check  # fail if graph.md is out of date (no write)
"""
from __future__ import annotations

import sys
from pathlib import Path

sys.path.insert(0, str(Path(__file__).resolve().parent))
from common import ROOT, load_yaml  # noqa: E402

CONCEPTS = ROOT / "curriculum" / "concepts.yaml"
OUT = ROOT / "curriculum" / "graph.md"
UNIT_NAMES = {0: "Unit 0 - Single-server backend", 1: "Unit 1 - Foundations", 2: "Unit 2 - Building blocks",
              3: "Unit 3 - Data", 4: "Unit 4 - Async and streams", 5: "Unit 5 - Consistency and coordination",
              6: "Unit 6 - Production reliability"}


def build(path: Path = CONCEPTS) -> str:
    concepts = (load_yaml(path) or {}).get("concepts") or []
    by_id = {c["id"]: c for c in concepts}
    if len(by_id) != len(concepts):
        raise SystemExit("duplicate concept ids")
    prereqs = {c["id"]: list(c.get("prerequisites") or []) for c in concepts}
    unknown = sorted({p for ps in prereqs.values() for p in ps if p not in by_id})
    if unknown:
        raise SystemExit(f"unknown prerequisite ids: {unknown}")
    dependents = {i: [] for i in by_id}
    for i, ps in prereqs.items():
        for p in ps:
            dependents[p].append(i)

    # depth = longest chain of prerequisites below the concept (roots = 0); also proves there is no cycle
    depth: dict[str, int] = {}

    def d(n: str, seen: tuple = ()) -> int:
        if n in seen:
            raise SystemExit("cycle: " + " -> ".join(seen[seen.index(n):] + (n,)))
        if n not in depth:
            depth[n] = 1 + max((d(p, seen + (n,)) for p in prereqs[n]), default=-1)
        return depth[n]

    for i in by_id:
        d(i)
    roots = [i for i, ps in prereqs.items() if not ps]  # validate.py reports roots outside Unit 0

    out = ["# Prerequisite graph", "",
           "> Generated by `python scripts/graph.py` from `curriculum/concepts.yaml`. Do not edit by hand.", "",
           f"{len(by_id)} concepts, {sum(len(p) for p in prereqs.values())} prerequisite edges, "
           f"longest chain {max(depth.values()) + 1} concepts. An arrow `A --> B` means: learn A before B.", "",
           f"Roots (no prerequisites): {', '.join(f'`{r}`' for r in roots)}. "
           f"Leaves (nothing depends on them): {', '.join(f'`{i}`' for i, ds in dependents.items() if not ds)}.", "",
           "```mermaid", "flowchart LR"]
    for u in sorted({c['unit'] for c in concepts}):
        out.append(f'  subgraph U{u}["{UNIT_NAMES.get(u, f"Unit {u}")}"]')
        out += [f"    {c['id'].replace('-', '_')}[\"{c['id']}\"]" for c in concepts if c["unit"] == u]
        out.append("  end")
    for c in concepts:
        for p in prereqs[c["id"]]:
            out.append(f"  {p.replace('-', '_')} --> {c['id'].replace('-', '_')}")
    out += ["```", "", "## Study order (one valid topological order, by depth)", ""]
    for k in range(max(depth.values()) + 1):
        ids = sorted((i for i in by_id if depth[i] == k), key=lambda i: (by_id[i]["unit"], i))
        out.append(f"- Level {k}: " + ", ".join(f"`{i}` (U{by_id[i]['unit']})" for i in ids))
    return "\n".join(out) + "\n"


if __name__ == "__main__":
    text = build()
    if "--check" in sys.argv:
        if not OUT.exists() or OUT.read_text(encoding="utf-8") != text:
            raise SystemExit("curriculum/graph.md is out of date: run python scripts/graph.py")
        print("graph.md is up to date")
    else:
        OUT.write_text(text, encoding="utf-8")
        print(f"Wrote: {OUT.relative_to(ROOT)}")
